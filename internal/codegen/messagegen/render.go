package messagegen

import (
	"bytes"
	"fmt"
	"go/format"
	"go/token"
	"path"
	"sort"
	"strconv"
	"strings"

	"github.com/saramand9/kpro/internal/codegen"
	"golang.org/x/mod/module"
)

// Options identifies the consumer module and project-relative output base.
type Options struct {
	Module string
	Output string
}

// BuildPlan renders types, a service contract, a checked message registrar
// adapter, and a create-once service implementation without writing to the
// project.
func BuildPlan(document Document, options Options) (codegen.Plan, error) {
	if err := document.Validate(); err != nil {
		return codegen.Plan{}, err
	}
	modulePath, output, err := validateOptions(options)
	if err != nil {
		return codegen.Plan{}, err
	}

	typesSource, err := renderTypes(document)
	if err != nil {
		return codegen.Plan{}, err
	}
	contractSource, err := renderContract(document, modulePath, output)
	if err != nil {
		return codegen.Plan{}, err
	}
	adapterSource, err := renderAdapter(document, modulePath, output)
	if err != nil {
		return codegen.Plan{}, err
	}
	scaffoldSource, err := renderScaffold(document, modulePath, output)
	if err != nil {
		return codegen.Plan{}, err
	}

	stem := fileIdentifier(document.Service)
	plan, err := codegen.BuildPlan(
		codegen.File{
			Path:      path.Join(output, "types", "messages_"+stem+".gen.go"),
			Content:   typesSource,
			Ownership: codegen.Generated,
		},
		codegen.File{
			Path:      path.Join(output, "contract", "service_"+stem+".gen.go"),
			Content:   contractSource,
			Ownership: codegen.Generated,
		},
		codegen.File{
			Path:      path.Join(output, "kpromessage", "routes_"+stem+".gen.go"),
			Content:   adapterSource,
			Ownership: codegen.Generated,
		},
		codegen.File{
			Path:      path.Join(output, "service", stem+".go"),
			Content:   scaffoldSource,
			Ownership: codegen.Scaffold,
		},
	)
	if err != nil {
		return codegen.Plan{}, fmt.Errorf("message codegen: build output plan: %w", err)
	}
	return plan, nil
}

// Generate is a concise alias for BuildPlan.
func Generate(document Document, options Options) (codegen.Plan, error) {
	return BuildPlan(document, options)
}

func validateOptions(options Options) (string, string, error) {
	if options.Module == "" || strings.TrimSpace(options.Module) != options.Module {
		return "", "", fmt.Errorf("%w: output module %q is invalid", ErrInvalidSpec, options.Module)
	}
	if err := module.CheckPath(options.Module); err != nil {
		return "", "", fmt.Errorf("%w: output module %q: %v", ErrInvalidSpec, options.Module, err)
	}

	output := options.Output
	if output == "" {
		output = "internal/message"
	}
	normalized, err := codegen.SafeRelativePath(output)
	if err != nil {
		return "", "", fmt.Errorf("%w: output path %q: %v", ErrInvalidSpec, output, err)
	}
	for _, segment := range strings.Split(normalized, "/") {
		if !token.IsIdentifier(segment) || token.Lookup(segment).IsKeyword() {
			return "", "", fmt.Errorf(
				"%w: output path segment %q is not a Go package identifier",
				ErrInvalidSpec,
				segment,
			)
		}
	}
	return options.Module, normalized, nil
}

func renderTypes(document Document) ([]byte, error) {
	var source bytes.Buffer
	source.WriteString("// Code generated by kpro message backend. DO NOT EDIT.\n")
	source.WriteString("package types\n\n")

	messages := orderedMessages(document.Messages)
	source.WriteString("const (\n")
	for _, message := range messages {
		goName := mustExportedIdentifier(message.Name)
		fmt.Fprintf(&source, "\t%sMessageID uint32 = %d\n", goName, message.ID)
	}
	source.WriteString(")\n\n")

	for _, message := range messages {
		goName := mustExportedIdentifier(message.Name)
		renderPayloadType(&source, goName+"Request", message.Request)
		if message.Response != nil {
			renderPayloadType(&source, goName+"Response", *message.Response)
		}
	}
	return formatGenerated("types", source.Bytes())
}

func renderPayloadType(source *bytes.Buffer, name string, payload Payload) {
	fmt.Fprintf(source, "type %s struct {\n", name)
	for _, field := range orderedFields(payload.Fields) {
		goName := mustExportedIdentifier(field.Name)
		fieldType := goType(field.Type)
		tag := field.Name
		if !field.Required {
			fieldType = "*" + fieldType
			tag += ",omitempty"
		}
		fmt.Fprintf(source, "\t%s %s `json:%s`\n", goName, fieldType, strconv.Quote(tag))
	}
	source.WriteString("}\n\n")
}

func renderContract(document Document, modulePath, output string) ([]byte, error) {
	var source bytes.Buffer
	typesImport := modulePath + "/" + output + "/types"
	serviceName := mustExportedIdentifier(document.Service) + "Service"

	source.WriteString("// Code generated by kpro message backend. DO NOT EDIT.\n")
	source.WriteString("package contract\n\n")
	source.WriteString("import (\n")
	source.WriteString("\t\"github.com/saramand9/kpro/core\"\n")
	fmt.Fprintf(&source, "\ttypes %q\n", typesImport)
	source.WriteString(")\n\n")
	fmt.Fprintf(&source, "type %s interface {\n", serviceName)
	for _, message := range orderedMessages(document.Messages) {
		goName := mustExportedIdentifier(message.Name)
		fmt.Fprintf(
			&source,
			"\t%s(core.Context, types.%sRequest)",
			goName,
			goName,
		)
		if message.Response == nil {
			source.WriteString(" error\n")
			continue
		}
		fmt.Fprintf(&source, " (types.%sResponse, error)\n", goName)
	}
	source.WriteString("}\n")
	return formatGenerated("contract", source.Bytes())
}

func renderAdapter(document Document, modulePath, output string) ([]byte, error) {
	var source bytes.Buffer
	baseImport := modulePath + "/" + output
	serviceGoName := mustExportedIdentifier(document.Service)
	serviceInterface := serviceGoName + "Service"
	registrarInterface := serviceGoName + "Registrar"
	bindingError := serviceGoName + "BindingError"

	source.WriteString("// Code generated by kpro message backend. DO NOT EDIT.\n")
	source.WriteString("package kpromessage\n\n")
	source.WriteString("import (\n")
	source.WriteString("\t\"bytes\"\n")
	source.WriteString("\t\"encoding/json\"\n")
	source.WriteString("\t\"fmt\"\n")
	source.WriteString("\t\"reflect\"\n")
	source.WriteString("\t\"sort\"\n\n")
	source.WriteString("\t\"github.com/saramand9/kpro/core\"\n")
	fmt.Fprintf(&source, "\tcontract %q\n", baseImport+"/contract")
	fmt.Fprintf(&source, "\ttypes %q\n", baseImport+"/types")
	source.WriteString(")\n\n")

	fmt.Fprintf(&source, "type %s struct {\n", bindingError)
	source.WriteString("\tMessage string\n")
	source.WriteString("\tMessageID uint32\n")
	source.WriteString("\tErr error\n")
	source.WriteString("}\n\n")
	fmt.Fprintf(&source, "func (err *%s) Error() string {\n", bindingError)
	source.WriteString("\tif err == nil { return \"message binding failed\" }\n")
	source.WriteString("\treturn fmt.Sprintf(\"bind message %q (%d): %v\", err.Message, err.MessageID, err.Err)\n")
	source.WriteString("}\n\n")
	fmt.Fprintf(&source, "func (err *%s) Unwrap() error {\n", bindingError)
	source.WriteString("\tif err == nil { return nil }\n")
	source.WriteString("\treturn err.Err\n")
	source.WriteString("}\n\n")

	fmt.Fprintf(
		&source,
		"// %s is the checked message-registration surface required by Register%s.\n",
		registrarInterface,
		serviceGoName,
	)
	fmt.Fprintf(&source, "type %s interface {\n", registrarInterface)
	source.WriteString("\tHandleSyncChecked(uint32, core.Handler) error\n")
	source.WriteString("\tHandleAsyncChecked(uint32, core.Handler) error\n")
	source.WriteString("}\n\n")

	fmt.Fprintf(
		&source,
		"// Register%s registers every %s message handler on registrar.\n",
		serviceGoName,
		serviceInterface,
	)
	fmt.Fprintf(
		&source,
		"func Register%s(registrar %s, service contract.%s) error {\n",
		serviceGoName,
		registrarInterface,
		serviceInterface,
	)
	fmt.Fprintf(
		&source,
		"\tif kpro%sNil(registrar) { return fmt.Errorf(\"message registrar is nil\") }\n",
		serviceGoName,
	)
	fmt.Fprintf(
		&source,
		"\tif kpro%sNil(service) { return fmt.Errorf(\"message service is nil\") }\n",
		serviceGoName,
	)
	for _, message := range orderedMessages(document.Messages) {
		goName := mustExportedIdentifier(message.Name)
		handlerName := unexportedIdentifier(goName) + "Handler"
		register := "HandleSyncChecked"
		if message.Dispatch == DispatchAsync {
			register = "HandleAsyncChecked"
		}
		fmt.Fprintf(
			&source,
			"\tif err := registrar.%s(types.%sMessageID, %s(service)); err != nil {\n",
			register,
			goName,
			handlerName,
		)
		fmt.Fprintf(
			&source,
			"\t\treturn fmt.Errorf(\"register message %s (%%d): %%w\", types.%sMessageID, err)\n",
			message.Name,
			goName,
		)
		source.WriteString("\t}\n")
	}
	source.WriteString("\treturn nil\n")
	source.WriteString("}\n\n")

	fmt.Fprintf(&source, "func kpro%sNil(value any) bool {\n", serviceGoName)
	source.WriteString("\tif value == nil { return true }\n")
	source.WriteString("\treflected := reflect.ValueOf(value)\n")
	source.WriteString("\tswitch reflected.Kind() {\n")
	source.WriteString("\tcase reflect.Chan, reflect.Func, reflect.Interface, reflect.Map, reflect.Pointer, reflect.Slice:\n")
	source.WriteString("\t\treturn reflected.IsNil()\n")
	source.WriteString("\tdefault:\n")
	source.WriteString("\t\treturn false\n")
	source.WriteString("\t}\n")
	source.WriteString("}\n\n")

	for _, message := range orderedMessages(document.Messages) {
		renderMessageHandler(&source, message, serviceInterface)
		renderMessageDecoder(&source, message, bindingError)
	}
	return formatGenerated("Router adapter", source.Bytes())
}

func renderMessageHandler(
	source *bytes.Buffer,
	message Message,
	serviceInterface string,
) {
	goName := mustExportedIdentifier(message.Name)
	handlerName := unexportedIdentifier(goName) + "Handler"
	fmt.Fprintf(
		source,
		"func %s(service contract.%s) core.Handler {\n",
		handlerName,
		serviceInterface,
	)
	source.WriteString("\treturn func(ctx core.Context) error {\n")
	fmt.Fprintf(
		source,
		"\t\trequest, err := decode%sRequest(ctx.Message().Data)\n",
		goName,
	)
	source.WriteString("\t\tif err != nil { return err }\n")
	if message.Response == nil {
		fmt.Fprintf(source, "\t\treturn service.%s(ctx, request)\n", goName)
		source.WriteString("\t}\n")
		source.WriteString("}\n\n")
		return
	}
	fmt.Fprintf(source, "\t\tresponse, err := service.%s(ctx, request)\n", goName)
	source.WriteString("\t\tif err != nil { return err }\n")
	source.WriteString("\t\tpayload, err := json.Marshal(response)\n")
	fmt.Fprintf(
		source,
		"\t\tif err != nil { return fmt.Errorf(\"encode %s response: %%w\", err) }\n",
		message.Name,
	)
	fmt.Fprintf(
		source,
		"\t\tif err := ctx.Reply(types.%sMessageID, payload); err != nil {\n",
		goName,
	)
	fmt.Fprintf(
		source,
		"\t\t\treturn fmt.Errorf(\"reply to %s: %%w\", err)\n",
		message.Name,
	)
	source.WriteString("\t\t}\n")
	source.WriteString("\t\treturn nil\n")
	source.WriteString("\t}\n")
	source.WriteString("}\n\n")
}

func renderMessageDecoder(source *bytes.Buffer, message Message, bindingError string) {
	goName := mustExportedIdentifier(message.Name)
	fields := orderedFields(message.Request.Fields)
	fmt.Fprintf(
		source,
		"func decode%sRequest(data []byte) (types.%sRequest, error) {\n",
		goName,
		goName,
	)
	fmt.Fprintf(source, "\tvar request types.%sRequest\n", goName)
	source.WriteString("\tvar rawFields map[string]json.RawMessage\n")
	source.WriteString("\tif err := json.Unmarshal(data, &rawFields); err != nil {\n")
	renderBindingErrorReturn(source, message, bindingError, "err")
	source.WriteString("\t}\n")
	source.WriteString("\tif rawFields == nil || bytes.Equal(bytes.TrimSpace(data), []byte(\"null\")) {\n")
	renderBindingErrorReturn(
		source,
		message,
		bindingError,
		`fmt.Errorf("request payload must be a JSON object")`,
	)
	source.WriteString("\t}\n")
	source.WriteString("\tvar unknownFields []string\n")
	source.WriteString("\tfor name := range rawFields {\n")
	source.WriteString("\t\tswitch name {\n")
	for _, field := range fields {
		fmt.Fprintf(source, "\t\tcase %s:\n", strconv.Quote(field.Name))
	}
	source.WriteString("\t\tdefault:\n")
	source.WriteString("\t\t\tunknownFields = append(unknownFields, name)\n")
	source.WriteString("\t\t}\n\t}\n")
	source.WriteString("\tif len(unknownFields) != 0 {\n")
	source.WriteString("\t\tsort.Strings(unknownFields)\n")
	renderBindingErrorReturn(
		source,
		message,
		bindingError,
		`fmt.Errorf("unknown field %q", unknownFields[0])`,
	)
	source.WriteString("\t}\n")
	for fieldIndex, field := range fields {
		goField := mustExportedIdentifier(field.Name)
		rawField := fmt.Sprintf("rawField%d", fieldIndex)
		fieldExists := fmt.Sprintf("field%dExists", fieldIndex)
		fmt.Fprintf(source, "\t%s, %s := rawFields[%s]\n", rawField, fieldExists, strconv.Quote(field.Name))
		if field.Required {
			fmt.Fprintf(source, "\tif !%s || bytes.Equal(bytes.TrimSpace(%s), []byte(\"null\")) {\n", fieldExists, rawField)
			renderBindingErrorReturn(
				source,
				message,
				bindingError,
				"fmt.Errorf("+strconv.Quote("required field "+field.Name+" is missing or null")+")",
			)
			source.WriteString("\t}\n")
			fmt.Fprintf(source, "\tif err := json.Unmarshal(%s, &request.%s); err != nil {\n", rawField, goField)
			renderBindingErrorReturn(
				source,
				message,
				bindingError,
				"fmt.Errorf("+strconv.Quote("field "+field.Name+": %w")+", err)",
			)
			source.WriteString("\t}\n")
			continue
		}
		fmt.Fprintf(source, "\tif %s && !bytes.Equal(bytes.TrimSpace(%s), []byte(\"null\")) {\n", fieldExists, rawField)
		fmt.Fprintf(source, "\t\tvar value %s\n", goType(field.Type))
		fmt.Fprintf(source, "\t\tif err := json.Unmarshal(%s, &value); err != nil {\n", rawField)
		renderBindingErrorReturn(
			source,
			message,
			bindingError,
			"fmt.Errorf("+strconv.Quote("field "+field.Name+": %w")+", err)",
		)
		source.WriteString("\t\t}\n")
		fmt.Fprintf(source, "\t\trequest.%s = &value\n", goField)
		source.WriteString("\t}\n")
	}
	source.WriteString("\treturn request, nil\n")
	source.WriteString("}\n\n")
}

func renderBindingErrorReturn(
	source *bytes.Buffer,
	message Message,
	bindingError string,
	errExpression string,
) {
	fmt.Fprintf(
		source,
		"\t\treturn request, &%s{Message: %q, MessageID: types.%sMessageID, Err: %s}\n",
		bindingError,
		message.Name,
		mustExportedIdentifier(message.Name),
		errExpression,
	)
}

func renderScaffold(document Document, modulePath, output string) ([]byte, error) {
	var source bytes.Buffer
	baseImport := modulePath + "/" + output
	serviceGoName := mustExportedIdentifier(document.Service)
	serviceType := serviceGoName + "Service"

	source.WriteString("// This file is created once by kpro and is safe to edit.\n")
	source.WriteString("package service\n\n")
	source.WriteString("import (\n")
	source.WriteString("\t\"github.com/saramand9/kpro/core\"\n")
	fmt.Fprintf(&source, "\tcontract %q\n", baseImport+"/contract")
	fmt.Fprintf(&source, "\ttypes %q\n", baseImport+"/types")
	source.WriteString(")\n\n")
	fmt.Fprintf(&source, "type %s struct{}\n\n", serviceType)
	fmt.Fprintf(
		&source,
		"var _ contract.%s = (*%s)(nil)\n\n",
		serviceType,
		serviceType,
	)
	for _, message := range orderedMessages(document.Messages) {
		goName := mustExportedIdentifier(message.Name)
		fmt.Fprintf(
			&source,
			"func (service *%s) %s(ctx core.Context, request types.%sRequest)",
			serviceType,
			goName,
			goName,
		)
		if message.Response == nil {
			source.WriteString(" error {\n")
			source.WriteString("\treturn nil\n")
			source.WriteString("}\n\n")
			continue
		}
		fmt.Fprintf(&source, " (types.%sResponse, error) {\n", goName)
		fmt.Fprintf(&source, "\tvar response types.%sResponse\n", goName)
		source.WriteString("\treturn response, nil\n")
		source.WriteString("}\n\n")
	}
	return formatGenerated("service scaffold", source.Bytes())
}

func formatGenerated(label string, source []byte) ([]byte, error) {
	formatted, err := format.Source(source)
	if err != nil {
		return nil, fmt.Errorf("message codegen: format %s: %w\n%s", label, err, source)
	}
	return formatted, nil
}

func orderedFields(fields []Field) []Field {
	ordered := append([]Field(nil), fields...)
	sort.Slice(ordered, func(left, right int) bool {
		if ordered[left].Name == ordered[right].Name {
			return ordered[left].Type < ordered[right].Type
		}
		return ordered[left].Name < ordered[right].Name
	})
	return ordered
}

func goType(fieldType FieldType) string {
	switch fieldType {
	case TypeString:
		return "string"
	case TypeBool:
		return "bool"
	case TypeInt32:
		return "int32"
	case TypeInt64:
		return "int64"
	case TypeUint32:
		return "uint32"
	case TypeUint64:
		return "uint64"
	case TypeFloat32:
		return "float32"
	case TypeFloat64:
		return "float64"
	case TypeBytes:
		return "[]byte"
	default:
		panic("messagegen: goType called before validation")
	}
}

func mustExportedIdentifier(value string) string {
	identifier, err := exportedIdentifier(value)
	if err != nil {
		panic("messagegen: identifier used before validation: " + err.Error())
	}
	return identifier
}

func unexportedIdentifier(value string) string {
	return strings.ToLower(value[:1]) + value[1:]
}

func fileIdentifier(value string) string {
	var result strings.Builder
	for _, character := range value {
		switch character {
		case '-':
			result.WriteByte('_')
		default:
			result.WriteString(strings.ToLower(string(character)))
		}
	}
	return result.String()
}
