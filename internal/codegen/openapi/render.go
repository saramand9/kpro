// Options identifies the target module and relative generated directory.
// Output defaults to internal/openapi. Module is required because generated
// packages deliberately import one another through the consumer's module path.
type Options struct {
	Module string
	Output string
}

// BuildPlan renders the independent IR into type, contract, KPro HTTP server,
// typed HTTP client, and application scaffold packages for the deliberately
// bounded CRUD subset. Unsupported operations fail before any output is
// created.
func BuildPlan(doc Document, options Options) (codegen.Plan, error) {
	if err := doc.Validate(); err != nil {
		return codegen.Plan{}, err
	}
	output, err := validateOptions(options)
	if err != nil {
		return codegen.Plan{}, err
	}
	typesSource, err := renderTypes(doc)
	if err != nil {
		return codegen.Plan{}, err
	}
	contractSource, err := renderContract(doc, options.Module, output)
	if err != nil {
		return codegen.Plan{}, err
	}
	httpSource, err := renderHTTP(doc, options.Module, output)
	if err != nil {
		return codegen.Plan{}, err
	}
	httpClientSource, err := renderHTTPClient(doc, options.Module, output)
	if err != nil {
		return codegen.Plan{}, err
	}
	scaffoldSource, err := renderScaffold(doc, options.Module, output)
	if err != nil {
		return codegen.Plan{}, err
	}
	return codegen.BuildPlan(
		codegen.File{Path: path.Join(output, "types", "types.gen.go"), Content: typesSource, Ownership: codegen.Generated},
		codegen.File{Path: path.Join(output, "contract", "contract.gen.go"), Content: contractSource, Ownership: codegen.Generated},
		codegen.File{Path: path.Join(output, "kprohttp", "routes.gen.go"), Content: httpSource, Ownership: codegen.Generated},
		codegen.File{Path: httpClientOutputPath(output), Content: httpClientSource, Ownership: codegen.Generated},
		codegen.File{Path: path.Join(output, "service", "api.go"), Content: scaffoldSource, Ownership: codegen.Scaffold},
	)
}

// Generate is a concise alias for BuildPlan.
func Generate(doc Document, options Options) (codegen.Plan, error) { return BuildPlan(doc, options) }

func renderTypes(doc Document) ([]byte, error) {
	var out bytes.Buffer
	out.WriteString("// Code generated by kpro OpenAPI backend. DO NOT EDIT.\npackage types\n")
	if len(doc.Components) != 0 {
		out.WriteString("\nimport (\n\t\"bytes\"\n\t\"encoding/json\"\n\t\"fmt\"\n)\n")
	}
	out.WriteString("\n")
	components := append([]Schema(nil), doc.Components...)
	sort.Slice(components, func(i, j int) bool { return components[i].Name < components[j].Name })
	if len(components) != 0 {
		renderJSONDecodeHelpers(&out)
		renderJSONValidationHelpers(&out)
	}
	for _, schema := range components {
		out.WriteString("type ")
		out.WriteString(schema.Name)
		out.WriteByte(' ')
		switch schema.Kind {
		case Object:
			out.WriteString("struct {\n")
			for _, field := range schema.Properties {
				out.WriteString(field.Name)
				out.WriteByte(' ')
				if !field.Required {
					out.WriteByte('*')
				}
				out.WriteString(goType(field.Type))
				out.WriteString(" `json:")
				out.WriteString(strconv.Quote(jsonTag(field)))
				out.WriteString("`\n")
			}
			out.WriteString("}\n\n")
		case Array:
			if schema.Items == nil {
				return nil, fmt.Errorf("openapi: component %q array has no items", schema.Name)
			}
			out.WriteString("[]")
			out.WriteString(goType(*schema.Items))
			out.WriteString("\n\n")
		default:
			out.WriteString(goType(TypeRef{Kind: schema.Kind}))
			out.WriteString("\n\n")
		}
		switch schema.Kind {
		case Object:
			renderObjectDecoder(&out, schema)
		case Array:
			renderArrayDecoder(&out, schema)
		case String, Integer, Number, Boolean:
			renderScalarDecoder(&out, schema)
		}
		renderSchemaJSONValidator(&out, schema)
	}
	return format.Source(out.Bytes())
}

func renderJSONDecodeHelpers(out *bytes.Buffer) {
	out.WriteString("func kproDecodeNonNull[T any](data []byte) (T, error) {\n")
	out.WriteString("\tvar zero T\n")
	out.WriteString("\tif bytes.Equal(bytes.TrimSpace(data), []byte(\"null\")) { return zero, fmt.Errorf(\"value must not be null\") }\n")
	out.WriteString("\tvar decoded T\n")
	out.WriteString("\tif err := json.Unmarshal(data, &decoded); err != nil { return zero, err }\n")
	out.WriteString("\treturn decoded, nil\n}\n\n")
	out.WriteString("func kproDecodeArray[T any](data []byte, decodeItem func([]byte) (T, error)) ([]T, error) {\n")
	out.WriteString("\tif bytes.Equal(bytes.TrimSpace(data), []byte(\"null\")) { return nil, fmt.Errorf(\"array must not be null\") }\n")
	out.WriteString("\tvar rawItems []json.RawMessage\n")
	out.WriteString("\tif err := json.Unmarshal(data, &rawItems); err != nil { return nil, err }\n")
	out.WriteString("\tdecoded := make([]T, len(rawItems))\n")
	out.WriteString("\tfor index, raw := range rawItems {\n")
	out.WriteString("\t\titem, err := decodeItem(raw)\n")
	out.WriteString("\t\tif err != nil { return nil, fmt.Errorf(\"array item %d: %w\", index, err) }\n")
	out.WriteString("\t\tdecoded[index] = item\n\t}\n")
	out.WriteString("\treturn decoded, nil\n}\n\n")
}

func renderJSONValidationHelpers(out *bytes.Buffer) {
	out.WriteString("func kproValidateJSONValue[T any](data []byte) error {\n")
	out.WriteString("\t_, err := kproDecodeNonNull[T](data)\n\treturn err\n}\n\n")
	out.WriteString("func kproValidateJSONArray(data []byte, validateItem func([]byte) error) error {\n")
	out.WriteString("\tif bytes.Equal(bytes.TrimSpace(data), []byte(\"null\")) { return fmt.Errorf(\"array must not be null\") }\n")
	out.WriteString("\tvar rawItems []json.RawMessage\n")
	out.WriteString("\tif err := json.Unmarshal(data, &rawItems); err != nil { return err }\n")
	out.WriteString("\tfor index, raw := range rawItems {\n")
	out.WriteString("\t\tif err := validateItem(raw); err != nil { return fmt.Errorf(\"array item %d: %w\", index, err) }\n\t}\n")
	out.WriteString("\treturn nil\n}\n\n")
}

func renderObjectDecoder(out *bytes.Buffer, schema Schema) {
	out.WriteString("func (value *")
	out.WriteString(schema.Name)
	out.WriteString(") UnmarshalJSON(data []byte) error {\n")
	out.WriteString("\tif value == nil { return fmt.Errorf(\"decode ")
	out.WriteString(schema.Name)
	out.WriteString(": target is nil\") }\n")
	out.WriteString("\tvar fields map[string]json.RawMessage\n")
	out.WriteString("\tif err := json.Unmarshal(data, &fields); err != nil { return err }\n")
	out.WriteString("\tif fields == nil || bytes.Equal(bytes.TrimSpace(data), []byte(\"null\")) { return fmt.Errorf(\"expected JSON object\") }\n")
	out.WriteString("\tvar decoded ")
	out.WriteString(schema.Name)
	out.WriteString("\n")
	for index, field := range schema.Properties {
		rawField := fmt.Sprintf("rawField%d", index)
		fieldExists := fmt.Sprintf("field%dExists", index)
		decodedField := fmt.Sprintf("decodedField%d", index)
		out.WriteString("\t")
		out.WriteString(rawField)
		out.WriteString(", ")
		out.WriteString(fieldExists)
		out.WriteString(" := fields[")
		out.WriteString(strconv.Quote(field.JSONName))
		out.WriteString("]\n")
		if field.Required {
			out.WriteString("\tif !")
			out.WriteString(fieldExists)
			out.WriteString(" || bytes.Equal(bytes.TrimSpace(")
			out.WriteString(rawField)
			out.WriteString("), []byte(\"null\")) {\n")
			out.WriteString("\t\treturn fmt.Errorf(\"required field %q is missing or null\", ")
			out.WriteString(strconv.Quote(field.JSONName))
			out.WriteString(")\n\t}\n")
		} else {
			out.WriteString("\tif ")
			out.WriteString(fieldExists)
			out.WriteString(" && bytes.Equal(bytes.TrimSpace(")
			out.WriteString(rawField)
			out.WriteString("), []byte(\"null\")) {\n")
			out.WriteString("\t\treturn fmt.Errorf(\"field %q must not be null\", ")
			out.WriteString(strconv.Quote(field.JSONName))
			out.WriteString(")\n\t}\n")
		}
		out.WriteString("\tif ")
		out.WriteString(fieldExists)
		out.WriteString(" {\n\t\t")
		out.WriteString(decodedField)
		out.WriteString(", err := ")
		out.WriteString(decodeTypeExpression(field.Type, rawField))
		out.WriteString("\n\t\tif err != nil { return fmt.Errorf(\"field %q: %w\", ")
		out.WriteString(strconv.Quote(field.JSONName))
		out.WriteString(", err) }\n\t\tdecoded.")
		out.WriteString(field.Name)
		out.WriteString(" = ")
		if !field.Required {
			out.WriteString("&")
		}
		out.WriteString(decodedField)
		out.WriteString("\n\t}\n")
	}
	out.WriteString("\t*value = decoded\n\treturn nil\n}\n\n")
}

func renderArrayDecoder(out *bytes.Buffer, schema Schema) {
	out.WriteString("func (value *")
	out.WriteString(schema.Name)
	out.WriteString(") UnmarshalJSON(data []byte) error {\n")
	out.WriteString("\tif value == nil { return fmt.Errorf(\"decode ")
	out.WriteString(schema.Name)
	out.WriteString(": target is nil\") }\n")
	out.WriteString("\tdecoded, err := ")
	out.WriteString(decodeTypeExpression(TypeRef{Kind: Array, Items: schema.Items}, "data"))
	out.WriteString("\n\tif err != nil { return err }\n\t*value = ")
	out.WriteString(schema.Name)
	out.WriteString("(decoded)\n\treturn nil\n}\n\n")
}

func renderScalarDecoder(out *bytes.Buffer, schema Schema) {
	out.WriteString("func (value *")
	out.WriteString(schema.Name)
	out.WriteString(") UnmarshalJSON(data []byte) error {\n")
	out.WriteString("\tif value == nil { return fmt.Errorf(\"decode ")
	out.WriteString(schema.Name)
	out.WriteString(": target is nil\") }\n")
	out.WriteString("\ttype kproJSONAlias ")
	out.WriteString(schema.Name)
	out.WriteString("\n\tdecoded, err := kproDecodeNonNull[kproJSONAlias](data)\n")
	out.WriteString("\tif err != nil { return err }\n\t*value = ")
	out.WriteString(schema.Name)
	out.WriteString("(decoded)\n\treturn nil\n}\n\n")
}

func decodeTypeExpression(ref TypeRef, data string) string {
	if ref.Kind == Array && ref.Name == "" && ref.Items != nil {
		return "kproDecodeArray[" + goType(*ref.Items) + "](" + data + ", " + decodeTypeFunction(*ref.Items) + ")"
	}
	return "kproDecodeNonNull[" + goType(ref) + "](" + data + ")"
}

func decodeTypeFunction(ref TypeRef) string {
	if ref.Kind != Array || ref.Name != "" || ref.Items == nil {
		return "kproDecodeNonNull[" + goType(ref) + "]"
	}
	return "func(data []byte) (" + goType(ref) + ", error) { return " + decodeTypeExpression(ref, "data") + " }"
}

func renderSchemaJSONValidator(out *bytes.Buffer, schema Schema) {
	validator := schemaJSONValidatorName(schema.Name)
	out.WriteString("func ")
	out.WriteString(validator)
	out.WriteString("(data []byte) error {\n")
	switch schema.Kind {
	case Object:
		out.WriteString("\tif bytes.Equal(bytes.TrimSpace(data), []byte(\"null\")) { return fmt.Errorf(\"object must not be null\") }\n")
		out.WriteString("\tvar fields map[string]json.RawMessage\n")
		out.WriteString("\tif err := json.Unmarshal(data, &fields); err != nil { return err }\n")
		out.WriteString("\tif fields == nil { return fmt.Errorf(\"expected JSON object\") }\n")
		for index, field := range schema.Properties {
			rawField := fmt.Sprintf("rawField%d", index)
			fieldExists := fmt.Sprintf("field%dExists", index)
			out.WriteString("\t")
			out.WriteString(rawField)
			out.WriteString(", ")
			out.WriteString(fieldExists)
			out.WriteString(" := fields[")
			out.WriteString(strconv.Quote(field.JSONName))
			out.WriteString("]\n")
			if field.Required {
				out.WriteString("\tif !")
				out.WriteString(fieldExists)
				out.WriteString(" || bytes.Equal(bytes.TrimSpace(")
				out.WriteString(rawField)
				out.WriteString("), []byte(\"null\")) { return fmt.Errorf(\"required field %q is missing or null\", ")
				out.WriteString(strconv.Quote(field.JSONName))
				out.WriteString(") }\n")
			} else {
				out.WriteString("\tif ")
				out.WriteString(fieldExists)
				out.WriteString(" && bytes.Equal(bytes.TrimSpace(")
				out.WriteString(rawField)
				out.WriteString("), []byte(\"null\")) { return fmt.Errorf(\"field %q must not be null\", ")
				out.WriteString(strconv.Quote(field.JSONName))
				out.WriteString(") }\n")
			}
			out.WriteString("\tif ")
			out.WriteString(fieldExists)
			out.WriteString(" {\n\t\tif err := ")
			out.WriteString(validateJSONTypeExpression(field.Type, rawField))
			out.WriteString("; err != nil { return fmt.Errorf(\"field %q: %w\", ")
			out.WriteString(strconv.Quote(field.JSONName))
			out.WriteString(", err) }\n\t}\n")
		}
		out.WriteString("\treturn nil\n")
	case Array:
		out.WriteString("\treturn ")
		out.WriteString(validateJSONTypeExpression(TypeRef{Kind: Array, Items: schema.Items}, "data"))
		out.WriteString("\n")
	case String, Integer, Number, Boolean:
		out.WriteString("\treturn kproValidateJSONValue[")
		out.WriteString(goType(TypeRef{Kind: schema.Kind}))
		out.WriteString("](data)\n")
	default:
		out.WriteString("\treturn fmt.Errorf(\"unsupported generated schema kind\")\n")
	}
	out.WriteString("}\n\n")
	out.WriteString("func (")
	out.WriteString(schema.Name)
	out.WriteString(") ValidateJSON(data []byte) error { return ")
	out.WriteString(validator)
	out.WriteString("(data) }\n\n")
}

func schemaJSONValidatorName(name string) string {
	return "kproValidateSchema" + name + "JSON"
}

func validateJSONTypeExpression(ref TypeRef, data string) string {
	if ref.Name != "" {
		return schemaJSONValidatorName(ref.Name) + "(" + data + ")"
	}
	if ref.Kind == Array && ref.Items != nil {
		return "kproValidateJSONArray(" + data + ", " + validateJSONTypeFunction(*ref.Items) + ")"
	}
	return "kproValidateJSONValue[" + goType(ref) + "](" + data + ")"
}

func validateJSONTypeFunction(ref TypeRef) string {
	if ref.Name != "" {
		return schemaJSONValidatorName(ref.Name)
	}
	if ref.Kind != Array || ref.Items == nil {
		return "kproValidateJSONValue[" + goType(ref) + "]"
	}
	return "func(data []byte) error { return " + validateJSONTypeExpression(ref, "data") + " }"
}

func renderContract(doc Document, module, output string) ([]byte, error) {
	var out bytes.Buffer
	typesImport := strings.TrimSuffix(module, "/") + "/" + output + "/types"
	out.WriteString("// Code generated by kpro OpenAPI backend. DO NOT EDIT.\npackage contract\n\n")
	out.WriteString("import (\n\t\"context\"\n")
	if usesTypes(doc) {
		out.WriteString("\ttypes \"")
		out.WriteString(typesImport)
		out.WriteString("\"\n")
	}
	out.WriteString(")\n\n")
	for _, operation := range doc.Operations {
		renderParams(&out, operation)
	}
	out.WriteString("type API interface {\n")
	for _, operation := range doc.Operations {
		out.WriteString(operation.ID)
		out.WriteString("(ctx context.Context")
		if len(operation.Parameters) != 0 {
			out.WriteString(", params ")
			out.WriteString(operation.ID)
			out.WriteString("Params")
		}
		if operation.Request != nil {
			out.WriteString(", request ")
			out.WriteString(contractType(*operation.Request))
		}
		out.WriteString(") (")
		if operation.Response == nil {
			out.WriteString("error")
		} else {
			out.WriteString(contractType(*operation.Response))
			out.WriteString(", error")
		}
		out.WriteString(")\n")
	}
	out.WriteString("}\n")
	return format.Source(out.Bytes())
}

func renderParams(out *bytes.Buffer, operation Operation) {
	if len(operation.Parameters) == 0 {
		return
	}
	out.WriteString("type ")
	out.WriteString(operation.ID)
	out.WriteString("Params struct {\n")
	for _, parameter := range operation.Parameters {
		out.WriteString(parameter.GoName)
		out.WriteByte(' ')
		if !parameter.Required {
			out.WriteByte('*')
		}
		out.WriteString(goType(parameter.Type))
		out.WriteString(" `json:")
		out.WriteString(strconv.Quote(parameter.Name))
		out.WriteString("`\n")
	}
	out.WriteString("}\n\n")
}

func renderScaffold(doc Document, module, output string) ([]byte, error) {
	var out bytes.Buffer
	base := strings.TrimSuffix(module, "/") + "/" + output
	out.WriteString("// API is a create-once starter implementation. Customize it for the service.\npackage service\n\n")
	out.WriteString("import (\n\t\"context\"\n\tcontract \"")
	out.WriteString(base + "/contract")
	out.WriteString("\"\n")
	if usesTypes(doc) {
		out.WriteString("\ttypes \"")
		out.WriteString(base + "/types")
		out.WriteString("\"\n")
	}
	out.WriteString(")\n\n")
	out.WriteString("type API struct{}\n\nvar _ contract.API = (*API)(nil)\n\n")
	for _, operation := range doc.Operations {
		out.WriteString("func (api *API) ")
		out.WriteString(operation.ID)
		out.WriteString("(ctx context.Context")
		if len(operation.Parameters) != 0 {
			out.WriteString(", params contract.")
			out.WriteString(operation.ID)
			out.WriteString("Params")
		}
		if operation.Request != nil {
			out.WriteString(", request ")
			out.WriteString(contractType(*operation.Request))
		}
		out.WriteString(") (")
		if operation.Response == nil {
			out.WriteString("error) { return nil }\n\n")
			continue
		}
		out.WriteString(contractType(*operation.Response))
		out.WriteString(", error) { var response ")
		out.WriteString(contractType(*operation.Response))
		out.WriteString("; return response, nil }\n\n")
	}
	return format.Source(out.Bytes())
}

func renderHTTP(doc Document, module, output string) ([]byte, error) {
	var out bytes.Buffer
	base := strings.TrimSuffix(module, "/") + "/" + output
	contractImport := base + "/contract"
	typesImport := base + "/types"
	out.WriteString("// Code generated by kpro OpenAPI backend. DO NOT EDIT.\npackage kprohttp\n\n")
	out.WriteString("import (\n\t\"fmt\"\n\t\"net/http\"\n\t\"reflect\"\n")
	if usesNumberParameters(doc) {
		out.WriteString("\t\"math\"\n")
	}
	if usesStrconv(doc) {
		out.WriteString("\t\"strconv\"\n")
	}
	if hasRequestBodies(doc) {
		out.WriteString("\t\"bytes\"\n\t\"mime\"\n")
	}
	if hasRequestBodies(doc) || hasResponseBodies(doc) {
		out.WriteString("\t\"encoding/json\"\n")
	}
	out.WriteString("\n\tcontract \"")
	out.WriteString(contractImport)
	out.WriteString("\"\n")
	if hasRequestBodies(doc) {
		out.WriteString("\ttypes \"")
		out.WriteString(typesImport)
		out.WriteString("\"\n")
	}
	out.WriteString("\t\"github.com/saramand9/kpro/transport/httpx\"\n)\n\n")
	out.WriteString("func isNilAPI(api contract.API) bool {\n")
	out.WriteString("\tif api == nil { return true }\n")
	out.WriteString("\tvalue := reflect.ValueOf(api)\n")
	out.WriteString("\tswitch value.Kind() {\n\tcase reflect.Chan, reflect.Func, reflect.Interface, reflect.Map, reflect.Pointer, reflect.Slice:\n\t\treturn value.IsNil()\n\tdefault:\n\t\treturn false\n\t}\n}\n\n")
	out.WriteString("func Register(endpoint *httpx.Endpoint, api contract.API) error {\n")
	out.WriteString("\tif endpoint == nil { return fmt.Errorf(\"openapi endpoint is nil\") }\n\tif isNilAPI(api) { return fmt.Errorf(\"openapi API is nil\") }\n")
	for _, operation := range doc.Operations {
		out.WriteString("\tif err := endpoint.HandleChecked(")
		out.WriteString(httpMethodConstant(operation.Method))
		out.WriteString(", ")
		out.WriteString(strconv.Quote(operation.Path))
		out.WriteString(", func(ctx *httpx.Context) error {\n")
		if len(operation.Parameters) != 0 {
			out.WriteString("\t\tvar params contract.")
			out.WriteString(operation.ID)
			out.WriteString("Params\n")
		}
		for _, parameter := range operation.Parameters {
			renderBinding(&out, parameter)
		}
		if operation.Request != nil {
			renderRequestBinding(&out, *operation.Request)
		}
		out.WriteString("\t\t")
		if operation.Response == nil {
			out.WriteString("if err := api.")
			out.WriteString(operation.ID)
			out.WriteString("(ctx.Context()")
			if len(operation.Parameters) != 0 {
				out.WriteString(", params")
			}
			if operation.Request != nil {
				out.WriteString(", request")
			}
			out.WriteString("); err != nil { return err }; ctx.WriteHeader(http.StatusNoContent); return nil\n")
		} else {
			out.WriteString("response, err := api.")
			out.WriteString(operation.ID)
			out.WriteString("(ctx.Context()")
			if len(operation.Parameters) != 0 {
				out.WriteString(", params")
			}
			if operation.Request != nil {
				out.WriteString(", request")
			}
			out.WriteString(")\n\t\tif err != nil { return err }\n")
			out.WriteString("\t\tresponseJSON, err := json.Marshal(response)\n")
			out.WriteString("\t\tif err != nil { return fmt.Errorf(\"encode ")
			out.WriteString(operation.ID)
			out.WriteString(" response: %w\", err) }\n")
			out.WriteString("\t\tif err := response.ValidateJSON(responseJSON); err != nil { return fmt.Errorf(\"validate ")
			out.WriteString(operation.ID)
			out.WriteString(" response: %w\", err) }\n")
			out.WriteString("\t\treturn ctx.Bytes(")
			out.WriteString(strconv.Itoa(operation.Status))
			out.WriteString(", \"application/json; charset=utf-8\", responseJSON)\n")
		}
		out.WriteString("\t}); err != nil { return fmt.Errorf(\"register ")
		out.WriteString(operation.ID)
		out.WriteString(": %w\", err) }\n")
	}
	out.WriteString("\treturn nil\n}\n")
	return format.Source(out.Bytes())
}

func renderRequestBinding(out *bytes.Buffer, request TypeRef) {
	out.WriteString("\t\tmediaType, _, mediaTypeErr := mime.ParseMediaType(ctx.Request().Header.Get(\"Content-Type\"))\n")
	out.WriteString("\t\tif mediaTypeErr != nil || mediaType != \"application/json\" { return ctx.Text(http.StatusUnsupportedMediaType, \"unsupported media type\") }\n")
	out.WriteString("\t\trequestBody, requestBodyErr := ctx.Body()\n")
	out.WriteString("\t\tif requestBodyErr != nil { return requestBodyErr }\n")
	out.WriteString("\t\tif bytes.Equal(bytes.TrimSpace(requestBody), []byte(\"null\")) { return ctx.Text(http.StatusBadRequest, \"invalid JSON body\") }\n")
	out.WriteString("\t\tvar request ")
	out.WriteString(contractType(request))
	out.WriteString("\n\t\tif err := json.Unmarshal(requestBody, &request); err != nil { return ctx.Text(http.StatusBadRequest, \"invalid JSON body\") }\n")
}

func httpMethodConstant(method string) string {
	switch method {
	case "GET":
		return "http.MethodGet"
	case "POST":
		return "http.MethodPost"
	case "PUT":
		return "http.MethodPut"
	case "PATCH":
		return "http.MethodPatch"
	case "DELETE":
		return "http.MethodDelete"
	default:
		return strconv.Quote(method)
	}
}

func renderBinding(out *bytes.Buffer, parameter Parameter) {
	var source string
	switch parameter.In {
	case "path":
		source = "ctx.Param(" + strconv.Quote(parameter.Name) + ")"
	case "query":
		source = "ctx.Query(" + strconv.Quote(parameter.Name) + ")"
	case "header":
		source = "ctx.Request().Header.Get(" + strconv.Quote(parameter.Name) + ")"
	}
	if parameter.Required {
		out.WriteString("\t\tif ")
		out.WriteString(source)
		out.WriteString(" == \"\" { return ctx.Text(http.StatusBadRequest, ")
		out.WriteString(strconv.Quote("missing required parameter " + parameter.Name))
		out.WriteString(") }\n")
	}
	name := "params." + parameter.GoName
	if !parameter.Required {
		out.WriteString("\t\tif valueText := ")
		out.WriteString(source)
		out.WriteString("; valueText != \"\" {\n")
		switch parameter.Type.Kind {
		case String:
			out.WriteString("\t\t\tparams.")
			out.WriteString(parameter.GoName)
			out.WriteString(" = &valueText\n")
		case Integer:
			out.WriteString("\t\t\tif value, err := strconv.ParseInt(valueText, 10, 64); err != nil { return ctx.Text(http.StatusBadRequest, ")
			out.WriteString(strconv.Quote("invalid parameter " + parameter.Name))
			out.WriteString(") } else { ")
			out.WriteString(name)
			out.WriteString(" = &value }\n")
		case Number:
			out.WriteString("\t\t\tif value, err := strconv.ParseFloat(valueText, 64); err != nil || math.IsNaN(value) || math.IsInf(value, 0) { return ctx.Text(http.StatusBadRequest, ")
			out.WriteString(strconv.Quote("invalid parameter " + parameter.Name))
			out.WriteString(") } else { ")
			out.WriteString(name)
			out.WriteString(" = &value }\n")
		case Boolean:
			out.WriteString("\t\t\tif value, err := strconv.ParseBool(valueText); err != nil { return ctx.Text(http.StatusBadRequest, ")
			out.WriteString(strconv.Quote("invalid parameter " + parameter.Name))
			out.WriteString(") } else { ")
			out.WriteString(name)
			out.WriteString(" = &value }\n")
		}
		out.WriteString("\t\t}\n")
		return
	}
	switch parameter.Type.Kind {
	case String:
		out.WriteString("\t\t")
		out.WriteString(name)
		out.WriteString(" = ")
		out.WriteString(source)
		out.WriteString("\n")
	case Integer:
		out.WriteString("\t\tif value, err := strconv.ParseInt(")
		out.WriteString(source)
		out.WriteString(", 10, 64); err != nil { return ctx.Text(http.StatusBadRequest, ")
		out.WriteString(strconv.Quote("invalid parameter " + parameter.Name))
		out.WriteString(") } else { ")
		out.WriteString(name)
		out.WriteString(" = value }\n")
	case Number:
		out.WriteString("\t\tif value, err := strconv.ParseFloat(")
		out.WriteString(source)
		out.WriteString(", 64); err != nil || math.IsNaN(value) || math.IsInf(value, 0) { return ctx.Text(http.StatusBadRequest, ")
		out.WriteString(strconv.Quote("invalid parameter " + parameter.Name))
		out.WriteString(") } else { ")
		out.WriteString(name)
		out.WriteString(" = value }\n")
	case Boolean:
		out.WriteString("\t\tif value, err := strconv.ParseBool(")
		out.WriteString(source)
		out.WriteString("); err != nil { return ctx.Text(http.StatusBadRequest, ")
		out.WriteString(strconv.Quote("invalid parameter " + parameter.Name))
		out.WriteString(") } else { ")
		out.WriteString(name)
		out.WriteString(" = value }\n")
	}
}

func goType(ref TypeRef) string {
	if ref.Name != "" {
		return ref.Name
	}
	switch ref.Kind {
	case String:
		return "string"
	case Integer:
		return "int64"
	case Number:
		return "float64"
	case Boolean:
		return "bool"
	case Array:
		if ref.Items != nil {
			return "[]" + goType(*ref.Items)
		}
	case Object:
		return "struct{}"
	}
	return "any"
}

func contractType(ref TypeRef) string {
	if ref.Name != "" {
		return "types." + ref.Name
	}
	if ref.Kind == Array && ref.Items != nil {
		if ref.Items.Name != "" {
			return "[]types." + ref.Items.Name
		}
		return "[]" + goType(*ref.Items)
	}
	return goType(ref)
}

func validateRequiredReferenceCycles(doc Document) error {
	objects := make(map[string]Schema)
	objectNames := make([]string, 0, len(doc.Components))
	for _, schema := range doc.Components {
		if schema.Kind == Object {
			objects[schema.Name] = schema
			objectNames = append(objectNames, schema.Name)
		}
	}
	state := make(map[string]uint8)
	positions := make(map[string]int)
	stack := make([]string, 0, len(objects))
	var visit func(string) error
	visit = func(name string) error {
		state[name] = 1
		positions[name] = len(stack)
		stack = append(stack, name)
		for _, field := range objects[name].Properties {
			if !field.Required || field.Type.Name == "" {
				continue
			}
			target := field.Type.Name
			if _, isObject := objects[target]; !isObject {
				continue
			}
			switch state[target] {
			case 0:
				if err := visit(target); err != nil {
					return err
				}
			case 1:
				cycle := append([]string(nil), stack[positions[target]:]...)
				cycle = append(cycle, target)
				return fmt.Errorf(
					"%w: required component reference cycle %s cannot be represented by Go value fields",
					ErrUnsupported,
					strings.Join(cycle, " -> "),
				)
			}
		}
		stack = stack[:len(stack)-1]
		delete(positions, name)
		state[name] = 2
		return nil
	}
	for _, name := range objectNames {
		if state[name] == 0 {
			if err := visit(name); err != nil {
				return err
			}
		}
	}
	return nil
}

func validateRoutePatterns(operations []Operation) error {
	mux := http.NewServeMux()
	for _, operation := range operations {
		pattern := operation.Method + " " + operation.Path
		if err := registerRoutePattern(mux, pattern); err != nil {
			return fmt.Errorf("openapi: route pattern %q: %w", pattern, err)
		}
	}
	return nil
}

func registerRoutePattern(mux *http.ServeMux, pattern string) (err error) {
	defer func() {
		if recovered := recover(); recovered != nil {
			err = fmt.Errorf("conflicts with another generated route or is invalid: %v", recovered)
		}
	}()
	mux.HandleFunc(pattern, func(http.ResponseWriter, *http.Request) {})
	return nil
}

func usesTypes(doc Document) bool {
	for _, operation := range doc.Operations {
		if (operation.Request != nil && operation.Request.Name != "") ||
			(operation.Response != nil && operation.Response.Name != "") {
			return true
		}
	}
	return false
}

func hasRequestBodies(doc Document) bool {
	for _, operation := range doc.Operations {
		if operation.Request != nil {
			return true
		}
	}
	return false
}

func hasResponseBodies(doc Document) bool {
	for _, operation := range doc.Operations {
		if operation.Response != nil {
			return true
		}
	}
	return false
}

func usesStrconv(doc Document) bool {
	for _, operation := range doc.Operations {
		for _, parameter := range operation.Parameters {
			if parameter.Type.Kind != String {
				return true
			}
		}
	}
	return false
}

func usesNumberParameters(doc Document) bool {
	for _, operation := range doc.Operations {
		for _, parameter := range operation.Parameters {
			if parameter.Type.Kind == Number {
				return true
			}
		}
	}
	return false
}

func jsonTag(field Field) string {
	if field.Required {
		return field.JSONName
	}
	return field.JSONName + ",omitempty"
}
