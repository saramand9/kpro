package openapi

import (
	"bytes"
	"fmt"
	"go/format"
	"path"
	"sort"
	"strconv"
	"strings"

	"github.com/saramand9/kpro/internal/codegen"
)

// Options identifies the target module and relative generated directory.
// Output defaults to internal/openapi. Module is required because generated
// packages deliberately import one another through the consumer's module path.
type Options struct {
	Module string
	Output string
}

// BuildPlan renders the independent IR into type, contract, and KPro HTTP
// adapter packages. The first adapter slice intentionally supports GET only;
// unsupported operations fail before any output is created.
func BuildPlan(doc Document, options Options) (codegen.Plan, error) {
	if strings.TrimSpace(options.Module) == "" {
		return codegen.Plan{}, fmt.Errorf("openapi: output module is required")
	}
	output := strings.Trim(strings.ReplaceAll(options.Output, `\`, "/"), "/")
	if output == "" {
		output = "internal/openapi"
	}
	for _, operation := range doc.Operations {
		if operation.Method != "GET" {
			return codegen.Plan{}, fmt.Errorf("%w: HTTP adapter for %s %s (only GET scalar binding is implemented)", ErrUnsupported, operation.Method, operation.Path)
		}
		if operation.Request != nil {
			return codegen.Plan{}, fmt.Errorf("%w: GET operation %q has a request body", ErrUnsupported, operation.ID)
		}
		for _, parameter := range operation.Parameters {
			if !scalar(parameter.Type.Kind) {
				return codegen.Plan{}, fmt.Errorf("%w: GET parameter %q is not scalar", ErrUnsupported, parameter.Name)
			}
		}
	}
	typesSource, err := renderTypes(doc)
	if err != nil {
		return codegen.Plan{}, err
	}
	contractSource, err := renderContract(doc, options.Module, output)
	if err != nil {
		return codegen.Plan{}, err
	}
	httpSource, err := renderHTTP(doc, options.Module, output)
	if err != nil {
		return codegen.Plan{}, err
	}
	scaffoldSource, err := renderScaffold(doc, options.Module, output)
	if err != nil {
		return codegen.Plan{}, err
	}
	return codegen.BuildPlan(
		codegen.File{Path: path.Join(output, "types", "types.gen.go"), Content: typesSource, Ownership: codegen.Generated},
		codegen.File{Path: path.Join(output, "contract", "contract.gen.go"), Content: contractSource, Ownership: codegen.Generated},
		codegen.File{Path: path.Join(output, "kprohttp", "routes.gen.go"), Content: httpSource, Ownership: codegen.Generated},
		codegen.File{Path: path.Join(output, "service", "api.go"), Content: scaffoldSource, Ownership: codegen.Scaffold},
	)
}

// Generate is a concise alias for BuildPlan.
func Generate(doc Document, options Options) (codegen.Plan, error) { return BuildPlan(doc, options) }

func renderTypes(doc Document) ([]byte, error) {
	var out bytes.Buffer
	out.WriteString("// Code generated by kpro OpenAPI backend. DO NOT EDIT.\npackage types\n\n")
	components := append([]Schema(nil), doc.Components...)
	sort.Slice(components, func(i, j int) bool { return components[i].Name < components[j].Name })
	for _, schema := range components {
		out.WriteString("type ")
		out.WriteString(schema.Name)
		out.WriteByte(' ')
		switch schema.Kind {
		case Object:
			out.WriteString("struct {\n")
			for _, field := range schema.Properties {
				out.WriteString(field.Name)
				out.WriteByte(' ')
				out.WriteString(goType(field.Type))
				out.WriteString(" `json:")
				out.WriteString(strconv.Quote(jsonTag(field)))
				out.WriteString("`\n")
			}
			out.WriteString("}\n\n")
		case Array:
			if schema.Items == nil {
				return nil, fmt.Errorf("openapi: component %q array has no items", schema.Name)
			}
			out.WriteString("[]")
			out.WriteString(goType(*schema.Items))
			out.WriteString("\n\n")
		default:
			out.WriteString(goType(TypeRef{Kind: schema.Kind}))
			out.WriteString("\n\n")
		}
	}
	return format.Source(out.Bytes())
}

func renderContract(doc Document, module, output string) ([]byte, error) {
	var out bytes.Buffer
	typesImport := strings.TrimSuffix(module, "/") + "/" + output + "/types"
	out.WriteString("// Code generated by kpro OpenAPI backend. DO NOT EDIT.\npackage contract\n\n")
	out.WriteString("import (\n\t\"context\"\n")
	if usesTypes(doc) {
		out.WriteString("\ttypes \"")
		out.WriteString(typesImport)
		out.WriteString("\"\n")
	}
	out.WriteString(")\n\n")
	for _, operation := range doc.Operations {
		renderParams(&out, operation)
	}
	out.WriteString("type API interface {\n")
	for _, operation := range doc.Operations {
		out.WriteString(operation.ID)
		out.WriteString("(context.Context")
		if len(operation.Parameters) != 0 {
			out.WriteString(", ")
			out.WriteString(operation.ID)
			out.WriteString("Params")
		}
		out.WriteString(") (")
		if operation.Response == nil {
			out.WriteString("error")
		} else {
			out.WriteString(contractType(*operation.Response))
			out.WriteString(", error")
		}
		out.WriteString(")\n")
	}
	out.WriteString("}\n")
	return format.Source(out.Bytes())
}

func renderParams(out *bytes.Buffer, operation Operation) {
	if len(operation.Parameters) == 0 {
		return
	}
	out.WriteString("type ")
	out.WriteString(operation.ID)
	out.WriteString("Params struct {\n")
	for _, parameter := range operation.Parameters {
		out.WriteString(parameter.GoName)
		out.WriteByte(' ')
		if !parameter.Required {
			out.WriteByte('*')
		}
		out.WriteString(goType(parameter.Type))
		out.WriteString(" `json:")
		out.WriteString(strconv.Quote(parameter.Name))
		out.WriteString("`\n")
	}
	out.WriteString("}\n\n")
}

func renderScaffold(doc Document, module, output string) ([]byte, error) {
	var out bytes.Buffer
	base := strings.TrimSuffix(module, "/") + "/" + output
	out.WriteString("// API is a create-once starter implementation. Customize it for the service.\npackage service\n\n")
	out.WriteString("import (\n\t\"context\"\n\tcontract \"")
	out.WriteString(base + "/contract")
	out.WriteString("\"\n")
	if usesTypes(doc) {
		out.WriteString("\ttypes \"")
		out.WriteString(base + "/types")
		out.WriteString("\"\n")
	}
	out.WriteString(")\n\n")
	out.WriteString("type API struct{}\n\nvar _ contract.API = (*API)(nil)\n\n")
	for _, operation := range doc.Operations {
		out.WriteString("func (api *API) ")
		out.WriteString(operation.ID)
		out.WriteString("(ctx context.Context")
		if len(operation.Parameters) != 0 {
			out.WriteString(", params contract.")
			out.WriteString(operation.ID)
			out.WriteString("Params")
		}
		out.WriteString(") (")
		if operation.Response == nil {
			out.WriteString("error) { return nil }\n\n")
			continue
		}
		out.WriteString(contractType(*operation.Response))
		out.WriteString(", error) { var response ")
		out.WriteString(contractType(*operation.Response))
		out.WriteString("; return response, nil }\n\n")
	}
	return format.Source(out.Bytes())
}

func renderHTTP(doc Document, module, output string) ([]byte, error) {
	var out bytes.Buffer
	contractImport := strings.TrimSuffix(module, "/") + "/" + output + "/contract"
	out.WriteString("// Code generated by kpro OpenAPI backend. DO NOT EDIT.\npackage kprohttp\n\n")
	out.WriteString("import (\n\t\"fmt\"\n\t\"net/http\"\n")
	if usesStrconv(doc) {
		out.WriteString("\t\"strconv\"\n")
	}
	out.WriteString("\n\tcontract \"")
	out.WriteString(contractImport)
	out.WriteString("\"\n\t\"github.com/saramand9/kpro/transport/httpx\"\n)\n\n")
	out.WriteString("func Register(endpoint *httpx.Endpoint, api contract.API) error {\n")
	out.WriteString("\tif endpoint == nil { return fmt.Errorf(\"openapi endpoint is nil\") }\n\tif api == nil { return fmt.Errorf(\"openapi API is nil\") }\n")
	for _, operation := range doc.Operations {
		out.WriteString("\tif err := endpoint.HandleChecked(http.MethodGet, ")
		out.WriteString(strconv.Quote(operation.Path))
		out.WriteString(", func(ctx *httpx.Context) error {\n")
		if len(operation.Parameters) != 0 {
			out.WriteString("\t\tvar params contract.")
			out.WriteString(operation.ID)
			out.WriteString("Params\n")
		}
		for _, parameter := range operation.Parameters {
			renderBinding(&out, parameter)
		}
		out.WriteString("\t\t")
		if operation.Response == nil {
			out.WriteString("if err := api.")
			out.WriteString(operation.ID)
			out.WriteString("(ctx.Context()")
			if len(operation.Parameters) != 0 {
				out.WriteString(", params")
			}
			out.WriteString("); err != nil { return err }; ctx.WriteHeader(http.StatusNoContent); return nil\n")
		} else {
			out.WriteString("response, err := api.")
			out.WriteString(operation.ID)
			out.WriteString("(ctx.Context()")
			if len(operation.Parameters) != 0 {
				out.WriteString(", params")
			}
			out.WriteString(")\n\t\tif err != nil { return err }\n\t\treturn ctx.JSON(")
			out.WriteString(strconv.Itoa(operation.Status))
			out.WriteString(", response)\n")
		}
		out.WriteString("\t}); err != nil { return fmt.Errorf(\"register ")
		out.WriteString(operation.ID)
		out.WriteString(": %w\", err) }\n")
	}
	out.WriteString("\treturn nil\n}\n")
	return format.Source(out.Bytes())
}

func renderBinding(out *bytes.Buffer, parameter Parameter) {
	var source string
	switch parameter.In {
	case "path":
		source = "ctx.Param(" + strconv.Quote(parameter.Name) + ")"
	case "query":
		source = "ctx.Query(" + strconv.Quote(parameter.Name) + ")"
	case "header":
		source = "ctx.Request().Header.Get(" + strconv.Quote(parameter.Name) + ")"
	}
	if parameter.Required {
		out.WriteString("\t\tif ")
		out.WriteString(source)
		out.WriteString(" == \"\" { return ctx.Text(http.StatusBadRequest, ")
		out.WriteString(strconv.Quote("missing required parameter " + parameter.Name))
		out.WriteString(") }\n")
	}
	name := "params." + parameter.GoName
	if !parameter.Required {
		out.WriteString("\t\tif valueText := ")
		out.WriteString(source)
		out.WriteString("; valueText != \"\" {\n")
		switch parameter.Type.Kind {
		case String:
			out.WriteString("\t\t\tparams.")
			out.WriteString(parameter.GoName)
			out.WriteString(" = &valueText\n")
		case Integer:
			out.WriteString("\t\t\tif value, err := strconv.ParseInt(valueText, 10, 64); err != nil { return ctx.Text(http.StatusBadRequest, ")
			out.WriteString(strconv.Quote("invalid parameter " + parameter.Name))
			out.WriteString(") } else { ")
			out.WriteString(name)
			out.WriteString(" = &value }\n")
		case Number:
			out.WriteString("\t\t\tif value, err := strconv.ParseFloat(valueText, 64); err != nil { return ctx.Text(http.StatusBadRequest, ")
			out.WriteString(strconv.Quote("invalid parameter " + parameter.Name))
			out.WriteString(") } else { ")
			out.WriteString(name)
			out.WriteString(" = &value }\n")
		case Boolean:
			out.WriteString("\t\t\tif value, err := strconv.ParseBool(valueText); err != nil { return ctx.Text(http.StatusBadRequest, ")
			out.WriteString(strconv.Quote("invalid parameter " + parameter.Name))
			out.WriteString(") } else { ")
			out.WriteString(name)
			out.WriteString(" = &value }\n")
		}
		out.WriteString("\t\t}\n")
		return
	}
	switch parameter.Type.Kind {
	case String:
		out.WriteString("\t\t")
		out.WriteString(name)
		out.WriteString(" = ")
		out.WriteString(source)
		out.WriteString("\n")
	case Integer:
		out.WriteString("\t\tif value, err := strconv.ParseInt(")
		out.WriteString(source)
		out.WriteString(", 10, 64); err != nil { return ctx.Text(http.StatusBadRequest, ")
		out.WriteString(strconv.Quote("invalid parameter " + parameter.Name))
		out.WriteString(") } else { ")
		out.WriteString(name)
		out.WriteString(" = value }\n")
	case Number:
		out.WriteString("\t\tif value, err := strconv.ParseFloat(")
		out.WriteString(source)
		out.WriteString(", 64); err != nil { return ctx.Text(http.StatusBadRequest, ")
		out.WriteString(strconv.Quote("invalid parameter " + parameter.Name))
		out.WriteString(") } else { ")
		out.WriteString(name)
		out.WriteString(" = value }\n")
	case Boolean:
		out.WriteString("\t\tif value, err := strconv.ParseBool(")
		out.WriteString(source)
		out.WriteString("); err != nil { return ctx.Text(http.StatusBadRequest, ")
		out.WriteString(strconv.Quote("invalid parameter " + parameter.Name))
		out.WriteString(") } else { ")
		out.WriteString(name)
		out.WriteString(" = value }\n")
	}
}

func goType(ref TypeRef) string {
	if ref.Name != "" {
		return ref.Name
	}
	switch ref.Kind {
	case String:
		return "string"
	case Integer:
		return "int64"
	case Number:
		return "float64"
	case Boolean:
		return "bool"
	case Array:
		if ref.Items != nil {
			return "[]" + goType(*ref.Items)
		}
	case Object:
		return "struct{}"
	}
	return "any"
}

func contractType(ref TypeRef) string {
	if ref.Name != "" {
		return "types." + ref.Name
	}
	if ref.Kind == Array && ref.Items != nil {
		if ref.Items.Name != "" {
			return "[]types." + ref.Items.Name
		}
		return "[]" + goType(*ref.Items)
	}
	return goType(ref)
}

func usesTypes(doc Document) bool {
	for _, operation := range doc.Operations {
		if operation.Response != nil && operation.Response.Name != "" {
			return true
		}
	}
	return false
}

func usesStrconv(doc Document) bool {
	for _, operation := range doc.Operations {
		for _, parameter := range operation.Parameters {
			if parameter.Type.Kind != String {
				return true
			}
		}
	}
	return false
}

func jsonTag(field Field) string {
	if field.Required {
		return field.JSONName
	}
	return field.JSONName + ",omitempty"
}
