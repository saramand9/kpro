func renderHTTPClient(doc Document, module, output string) ([]byte, error) {
	var source bytes.Buffer
	base := strings.TrimSuffix(module, "/") + "/" + output

	source.WriteString("// Code generated by kpro OpenAPI backend. DO NOT EDIT.\n")
	source.WriteString("package kprohttpclient\n\n")
	source.WriteString("import (\n")
	source.WriteString("\t\"bytes\"\n")
	source.WriteString("\t\"context\"\n")
	if hasRequestBodies(doc) || hasResponseBodies(doc) {
		source.WriteString("\t\"encoding/json\"\n")
	}
	source.WriteString("\t\"fmt\"\n")
	source.WriteString("\t\"io\"\n")
	source.WriteString("\t\"mime\"\n")
	if usesNumberParameters(doc) {
		source.WriteString("\t\"math\"\n")
	}
	source.WriteString("\t\"net/http\"\n")
	source.WriteString("\t\"net/url\"\n")
	source.WriteString("\t\"reflect\"\n")
	if usesStrconv(doc) {
		source.WriteString("\t\"strconv\"\n")
	}
	source.WriteString("\t\"strings\"\n")
	source.WriteString("\t\"time\"\n\n")
	fmt.Fprintf(&source, "\tcontract %q\n", base+"/contract")
	if usesTypes(doc) {
		fmt.Fprintf(&source, "\ttypes %q\n", base+"/types")
	}
	source.WriteString(")\n\n")

	renderHTTPClientFoundation(&source)
	for _, operation := range doc.Operations {
		if err := renderHTTPClientOperation(&source, operation); err != nil {
			return nil, err
		}
	}
	formatted, err := format.Source(source.Bytes())
	if err != nil {
		return nil, fmt.Errorf("openapi: format HTTP client: %w", err)
	}
	return formatted, nil
}

func renderHTTPClientFoundation(source *bytes.Buffer) {
	source.WriteString("const (\n")
	source.WriteString("\tDefaultTimeout = 30 * time.Second\n")
	source.WriteString("\tDefaultMaxResponseBytes int64 = 4 << 20\n")
	source.WriteString(")\n\n")
	source.WriteString("// Doer is the narrow HTTP execution surface used by Client.\n")
	source.WriteString("type Doer interface {\n")
	source.WriteString("\tDo(*http.Request) (*http.Response, error)\n")
	source.WriteString("}\n\n")
	source.WriteString("// Config configures a generated HTTP client.\n")
	source.WriteString("type Config struct {\n")
	source.WriteString("\tBaseURL string\n")
	source.WriteString("\tHTTPClient Doer\n")
	source.WriteString("\tMaxResponseBytes int64\n")
	source.WriteString("}\n\n")
	source.WriteString("// Client implements the generated application contract over HTTP.\n")
	source.WriteString("type Client struct {\n")
	source.WriteString("\tbaseURL string\n")
	source.WriteString("\thttpClient Doer\n")
	source.WriteString("\tmaxResponseBytes int64\n")
	source.WriteString("}\n\n")
	source.WriteString("var _ contract.API = (*Client)(nil)\n\n")
	source.WriteString("// ResponseError reports a bounded non-success HTTP response.\n")
	source.WriteString("type ResponseError struct {\n")
	source.WriteString("\tStatusCode int\n")
	source.WriteString("\tHeader http.Header\n")
	source.WriteString("\tBody []byte\n")
	source.WriteString("\tTruncated bool\n")
	source.WriteString("\tCause error\n")
	source.WriteString("}\n\n")
	source.WriteString("func (err *ResponseError) Error() string {\n")
	source.WriteString("\tif err == nil { return \"unexpected HTTP response\" }\n")
	source.WriteString("\treturn fmt.Sprintf(\"unexpected HTTP response status %d\", err.StatusCode)\n")
	source.WriteString("}\n\n")
	source.WriteString("func (err *ResponseError) Unwrap() error {\n")
	source.WriteString("\tif err == nil { return nil }\n")
	source.WriteString("\treturn err.Cause\n")
	source.WriteString("}\n\n")
	source.WriteString("// New validates config and constructs a generated HTTP client.\n")
	source.WriteString("func New(config Config) (*Client, error) {\n")
	source.WriteString("\tif config.BaseURL == \"\" || strings.TrimSpace(config.BaseURL) != config.BaseURL {\n")
	source.WriteString("\t\treturn nil, fmt.Errorf(\"HTTP client base URL must be non-empty and have no surrounding whitespace\")\n")
	source.WriteString("\t}\n")
	source.WriteString("\tbaseURL, err := url.Parse(config.BaseURL)\n")
	source.WriteString("\tif err != nil { return nil, fmt.Errorf(\"parse HTTP client base URL: %w\", err) }\n")
	source.WriteString("\tif baseURL.Opaque != \"\" || (baseURL.Scheme != \"http\" && baseURL.Scheme != \"https\") || baseURL.Host == \"\" {\n")
	source.WriteString("\t\treturn nil, fmt.Errorf(\"HTTP client base URL must be an absolute http or https URL\")\n")
	source.WriteString("\t}\n")
	source.WriteString("\tif baseURL.User != nil { return nil, fmt.Errorf(\"HTTP client base URL must not contain user information\") }\n")
	source.WriteString("\tif baseURL.RawQuery != \"\" || baseURL.ForceQuery || baseURL.Fragment != \"\" {\n")
	source.WriteString("\t\treturn nil, fmt.Errorf(\"HTTP client base URL must not contain a query or fragment\")\n")
	source.WriteString("\t}\n")
	source.WriteString("\tif err := kproHTTPClientValidateBasePath(baseURL); err != nil { return nil, err }\n")
	source.WriteString("\thttpClient := config.HTTPClient\n")
	source.WriteString("\tif httpClient == nil {\n")
	source.WriteString("\t\thttpClient = &http.Client{\n")
	source.WriteString("\t\t\tTimeout: DefaultTimeout,\n")
	source.WriteString("\t\t\tCheckRedirect: func(*http.Request, []*http.Request) error { return http.ErrUseLastResponse },\n")
	source.WriteString("\t\t}\n")
	source.WriteString("\t} else if kproHTTPClientNil(httpClient) {\n")
	source.WriteString("\t\treturn nil, fmt.Errorf(\"HTTP client is typed nil\")\n")
	source.WriteString("\t}\n")
	source.WriteString("\tmaxResponseBytes := config.MaxResponseBytes\n")
	source.WriteString("\tif maxResponseBytes == 0 { maxResponseBytes = DefaultMaxResponseBytes }\n")
	source.WriteString("\tif maxResponseBytes < 0 { return nil, fmt.Errorf(\"HTTP client max response bytes must not be negative\") }\n")
	source.WriteString("\treturn &Client{\n")
	source.WriteString("\t\tbaseURL: strings.TrimRight(baseURL.String(), \"/\"),\n")
	source.WriteString("\t\thttpClient: httpClient,\n")
	source.WriteString("\t\tmaxResponseBytes: maxResponseBytes,\n")
	source.WriteString("\t}, nil\n")
	source.WriteString("}\n\n")
	source.WriteString("func kproHTTPClientNil(value any) bool {\n")
	source.WriteString("\tif value == nil { return true }\n")
	source.WriteString("\treflected := reflect.ValueOf(value)\n")
	source.WriteString("\tswitch reflected.Kind() {\n")
	source.WriteString("\tcase reflect.Chan, reflect.Func, reflect.Interface, reflect.Map, reflect.Pointer, reflect.Slice:\n")
	source.WriteString("\t\treturn reflected.IsNil()\n")
	source.WriteString("\tdefault:\n")
	source.WriteString("\t\treturn false\n")
	source.WriteString("\t}\n")
	source.WriteString("}\n\n")
	source.WriteString("func kproHTTPClientValidateBasePath(baseURL *url.URL) error {\n")
	source.WriteString("\tdecoded, err := url.PathUnescape(baseURL.EscapedPath())\n")
	source.WriteString("\tif err != nil { return fmt.Errorf(\"HTTP client base URL has an invalid path: %w\", err) }\n")
	source.WriteString("\tif strings.Contains(decoded, \"//\") {\n")
	source.WriteString("\t\treturn fmt.Errorf(\"HTTP client base URL path must not contain duplicate slashes\")\n")
	source.WriteString("\t}\n")
	source.WriteString("\tfor _, segment := range strings.Split(decoded, \"/\") {\n")
	source.WriteString("\t\tif segment == \".\" || segment == \"..\" {\n")
	source.WriteString("\t\t\treturn fmt.Errorf(\"HTTP client base URL path must not contain dot segments\")\n")
	source.WriteString("\t\t}\n")
	source.WriteString("\t}\n")
	source.WriteString("\treturn nil\n")
	source.WriteString("}\n\n")
	source.WriteString("func kproHTTPClientEscapePathSegment(value string) string {\n")
	source.WriteString("\tswitch value {\n")
	source.WriteString("\tcase \".\":\n")
	source.WriteString("\t\treturn \"%2E\"\n")
	source.WriteString("\tcase \"..\":\n")
	source.WriteString("\t\treturn \"%2E%2E\"\n")
	source.WriteString("\tdefault:\n")
	source.WriteString("\t\treturn url.PathEscape(value)\n")
	source.WriteString("\t}\n")
	source.WriteString("}\n\n")
	source.WriteString("func kproHTTPClientPathParameter(operationPath, name, value string) string {\n")
	source.WriteString("\treturn strings.ReplaceAll(operationPath, \"{\"+name+\"}\", kproHTTPClientEscapePathSegment(value))\n")
	source.WriteString("}\n\n")
	source.WriteString("func kproHTTPClientValidateHeaderValue(value string) error {\n")
	source.WriteString("\tfor index := 0; index < len(value); index++ {\n")
	source.WriteString("\t\tcharacter := value[index]\n")
	source.WriteString("\t\tif character == 0x7f || (character < 0x20 && character != '\\t') {\n")
	source.WriteString("\t\t\treturn fmt.Errorf(\"contains a prohibited control character\")\n")
	source.WriteString("\t\t}\n")
	source.WriteString("\t}\n")
	source.WriteString("\treturn nil\n")
	source.WriteString("}\n\n")
	renderHTTPClientDo(source)
	renderHTTPClientReadBounded(source)
}

func renderHTTPClientDo(source *bytes.Buffer) {
	source.WriteString("func (client *Client) do(\n")
	source.WriteString("\tctx context.Context, method, operationPath string,\n")
	source.WriteString("\tquery url.Values, header http.Header, body []byte,\n")
	source.WriteString("\texpectedStatus int, expectsJSON bool,\n")
	source.WriteString(") ([]byte, error) {\n")
	source.WriteString("\tif client == nil { return nil, fmt.Errorf(\"HTTP client is nil\") }\n")
	source.WriteString("\tif client.baseURL == \"\" || kproHTTPClientNil(client.httpClient) || client.maxResponseBytes <= 0 {\n")
	source.WriteString("\t\treturn nil, fmt.Errorf(\"HTTP client is not initialized; construct it with New\")\n")
	source.WriteString("\t}\n")
	source.WriteString("\ttarget := client.baseURL + operationPath\n")
	source.WriteString("\tif encodedQuery := query.Encode(); encodedQuery != \"\" { target += \"?\" + encodedQuery }\n")
	source.WriteString("\tvar bodyReader io.Reader\n")
	source.WriteString("\tif body != nil { bodyReader = bytes.NewReader(body) }\n")
	source.WriteString("\trequest, err := http.NewRequestWithContext(ctx, method, target, bodyReader)\n")
	source.WriteString("\tif err != nil { return nil, fmt.Errorf(\"build HTTP request: %w\", err) }\n")
	source.WriteString("\trequest.Header = header.Clone()\n")
	source.WriteString("\tif request.Header == nil { request.Header = make(http.Header) }\n")
	source.WriteString("\tif body != nil { request.Header.Set(\"Content-Type\", \"application/json\") }\n")
	source.WriteString("\tif expectsJSON && request.Header.Get(\"Accept\") == \"\" { request.Header.Set(\"Accept\", \"application/json\") }\n")
	source.WriteString("\tresponse, err := client.httpClient.Do(request)\n")
	source.WriteString("\tif err != nil {\n")
	source.WriteString("\t\tif response != nil && !kproHTTPClientNil(response.Body) { _ = response.Body.Close() }\n")
	source.WriteString("\t\treturn nil, fmt.Errorf(\"perform HTTP request: %w\", err)\n")
	source.WriteString("\t}\n")
	source.WriteString("\tif response == nil { return nil, fmt.Errorf(\"perform HTTP request: client returned a nil response\") }\n")
	source.WriteString("\tif response.StatusCode != expectedStatus {\n")
	source.WriteString("\t\tresponseError := &ResponseError{StatusCode: response.StatusCode, Header: response.Header.Clone()}\n")
	source.WriteString("\t\tif kproHTTPClientNil(response.Body) {\n")
	source.WriteString("\t\t\tresponseError.Cause = fmt.Errorf(\"HTTP response body is nil\")\n")
	source.WriteString("\t\t\treturn nil, responseError\n")
	source.WriteString("\t\t}\n")
	source.WriteString("\t\tdefer response.Body.Close()\n")
	source.WriteString("\t\tresponseError.Body, responseError.Truncated, responseError.Cause = kproHTTPClientReadBounded(response.Body, client.maxResponseBytes)\n")
	source.WriteString("\t\treturn nil, responseError\n")
	source.WriteString("\t}\n")
	source.WriteString("\tif kproHTTPClientNil(response.Body) { return nil, fmt.Errorf(\"perform HTTP request: response body is nil\") }\n")
	source.WriteString("\tdefer response.Body.Close()\n")
	source.WriteString("\tresponseBody, truncated, err := kproHTTPClientReadBounded(response.Body, client.maxResponseBytes)\n")
	source.WriteString("\tif err != nil { return nil, fmt.Errorf(\"read HTTP response: %w\", err) }\n")
	source.WriteString("\tif truncated { return nil, fmt.Errorf(\"HTTP response exceeds %d bytes\", client.maxResponseBytes) }\n")
	source.WriteString("\tif !expectsJSON {\n")
	source.WriteString("\t\tif len(responseBody) != 0 { return nil, fmt.Errorf(\"HTTP response status %d must not contain a body\", expectedStatus) }\n")
	source.WriteString("\t\treturn nil, nil\n")
	source.WriteString("\t}\n")
	source.WriteString("\tmediaType, _, err := mime.ParseMediaType(response.Header.Get(\"Content-Type\"))\n")
	source.WriteString("\tif err != nil || mediaType != \"application/json\" {\n")
	source.WriteString("\t\treturn nil, fmt.Errorf(\"HTTP response has unsupported media type %q\", response.Header.Get(\"Content-Type\"))\n")
	source.WriteString("\t}\n")
	source.WriteString("\treturn responseBody, nil\n")
	source.WriteString("}\n\n")
}

func renderHTTPClientReadBounded(source *bytes.Buffer) {
	source.WriteString("func kproHTTPClientReadBounded(reader io.Reader, limit int64) ([]byte, bool, error) {\n")
	source.WriteString("\tlimited := &io.LimitedReader{R: reader, N: limit}\n")
	source.WriteString("\tdata, err := io.ReadAll(limited)\n")
	source.WriteString("\tif err != nil { return data, false, err }\n")
	source.WriteString("\tif limited.N != 0 { return data, false, nil }\n")
	source.WriteString("\tvar extra [1]byte\n")
	source.WriteString("\tread, err := io.ReadFull(reader, extra[:])\n")
	source.WriteString("\tif err == io.EOF && read == 0 { return data, false, nil }\n")
	source.WriteString("\tif err != nil { return data, false, err }\n")
	source.WriteString("\treturn data, true, nil\n")
	source.WriteString("}\n\n")
}

func renderHTTPClientOperation(source *bytes.Buffer, operation Operation) error {
	fmt.Fprintf(source, "func (client *Client) %s(ctx context.Context", operation.ID)
	if len(operation.Parameters) != 0 {
		fmt.Fprintf(source, ", params contract.%sParams", operation.ID)
	}
	if operation.Request != nil {
		fmt.Fprintf(source, ", request %s", contractType(*operation.Request))
	}
	source.WriteString(") (")
	if operation.Response == nil {
		source.WriteString("error")
	} else {
		fmt.Fprintf(source, "%s, error", contractType(*operation.Response))
	}
	source.WriteString(") {\n")
	if operation.Response != nil {
		fmt.Fprintf(source, "\tvar response %s\n", contractType(*operation.Response))
	}
	fmt.Fprintf(source, "\toperationPath := %s\n", strconv.Quote(operation.Path))
	source.WriteString("\tquery := make(url.Values)\n")
	source.WriteString("\theader := make(http.Header)\n")
	for _, parameter := range operation.Parameters {
		if err := renderHTTPClientParameter(source, operation, parameter); err != nil {
			return err
		}
	}
	source.WriteString("\tvar requestBody []byte\n")
	source.WriteString("\tvar err error\n")
	if operation.Request != nil {
		source.WriteString("\trequestBody, err = json.Marshal(request)\n")
		fmt.Fprintf(source, "\tif err != nil { return %s }\n", clientOperationErrorReturn(operation, "encode request: ", "err"))
		source.WriteString("\tif err := request.ValidateJSON(requestBody); err != nil {\n")
		fmt.Fprintf(source, "\t\treturn %s\n", clientOperationErrorReturn(operation, "validate request: ", "err"))
		source.WriteString("\t}\n")
	}
	responseTarget := "responseBody, err :="
	if operation.Response == nil {
		responseTarget = "_, err ="
	}
	fmt.Fprintf(source, "\t%s client.do(ctx, %s, operationPath, query, header, requestBody, %d, %t)\n",
		responseTarget, httpMethodConstant(operation.Method), operation.Status, operation.Response != nil)
	source.WriteString("\tif err != nil {\n")
	fmt.Fprintf(source, "\t\treturn %s\n", clientOperationErrorReturn(operation, "", "err"))
	source.WriteString("\t}\n")
	if operation.Response == nil {
		source.WriteString("\treturn nil\n")
		source.WriteString("}\n\n")
		return nil
	}
	source.WriteString("\tif err := json.Unmarshal(responseBody, &response); err != nil {\n")
	fmt.Fprintf(source, "\t\treturn %s\n", clientOperationErrorReturn(operation, "decode response: ", "err"))
	source.WriteString("\t}\n")
	source.WriteString("\tif err := response.ValidateJSON(responseBody); err != nil {\n")
	fmt.Fprintf(source, "\t\treturn %s\n", clientOperationErrorReturn(operation, "validate response: ", "err"))
	source.WriteString("\t}\n")
	source.WriteString("\treturn response, nil\n")
	source.WriteString("}\n\n")
	return nil
}

func renderHTTPClientParameter(source *bytes.Buffer, operation Operation, parameter Parameter) error {
	value := "params." + parameter.GoName
	indent := "\t"
	if !parameter.Required {
		fmt.Fprintf(source, "\tif %s != nil {\n", value)
		value = "*" + value
		indent = "\t\t"
	}
	if parameter.Type.Kind == String {
		fmt.Fprintf(source, "%sif %s == \"\" {\n", indent, value)
		fmt.Fprintf(
			source,
			"%s\treturn %s\n",
			indent,
			clientOperationErrorReturn(operation, "parameter "+parameter.Name+": ", "fmt.Errorf(\"value must not be empty\")"),
		)
		fmt.Fprintf(source, "%s}\n", indent)
	}
	if parameter.Type.Kind == Number {
		fmt.Fprintf(source, "%sif math.IsNaN(%s) || math.IsInf(%s, 0) {\n", indent, value, value)
		fmt.Fprintf(
			source,
			"%s\treturn %s\n",
			indent,
			clientOperationErrorReturn(operation, "parameter "+parameter.Name+": ", "fmt.Errorf(\"value must be finite\")"),
		)
		fmt.Fprintf(source, "%s}\n", indent)
	}
	text, err := clientParameterText(parameter.Type, value)
	if err != nil {
		return fmt.Errorf("openapi: render HTTP client parameter %q: %w", parameter.Name, err)
	}
	switch parameter.In {
	case "path":
		fmt.Fprintf(source, "%soperationPath = kproHTTPClientPathParameter(operationPath, %s, %s)\n", indent, strconv.Quote(parameter.Name), text)
	case "query":
		fmt.Fprintf(source, "%squery.Set(%s, %s)\n", indent, strconv.Quote(parameter.Name), text)
	case "header":
		fmt.Fprintf(source, "%sif err := kproHTTPClientValidateHeaderValue(%s); err != nil {\n", indent, text)
		fmt.Fprintf(
			source,
			"%s\treturn %s\n",
			indent,
			clientOperationErrorReturn(operation, "parameter "+parameter.Name+": ", "err"),
		)
		fmt.Fprintf(source, "%s}\n", indent)
		fmt.Fprintf(source, "%sheader.Set(%s, %s)\n", indent, strconv.Quote(parameter.Name), text)
	default:
		return fmt.Errorf("openapi: render HTTP client parameter %q in unsupported location %q", parameter.Name, parameter.In)
	}
	if !parameter.Required {
		source.WriteString("\t}\n")
	}
	return nil
}

func clientParameterText(ref TypeRef, value string) (string, error) {
	switch ref.Kind {
	case String:
		return value, nil
	case Integer:
		return "strconv.FormatInt(" + value + ", 10)", nil
	case Number:
		return "strconv.FormatFloat(" + value + ", 'g', -1, 64)", nil
	case Boolean:
		return "strconv.FormatBool(" + value + ")", nil
	default:
		return "", fmt.Errorf("unsupported parameter kind %q", ref.Kind)
	}
}

func clientOperationErrorReturn(operation Operation, detail, errExpression string) string {
	wrapped := fmt.Sprintf(
		`fmt.Errorf("%%s: %%s%%w", %q, %q, %s)`,
		operation.ID,
		detail,
		errExpression,
	)
	if operation.Response == nil {
		return wrapped
	}
	return "response, " + wrapped
}

func httpClientOutputPath(output string) string {
	return path.Join(output, "kprohttpclient", "client.gen.go")
}
